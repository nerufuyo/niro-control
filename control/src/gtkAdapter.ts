// @ts-nocheck: Gio / GLib are untyped here
// The GTK appearance adapter: a generated stylesheet that GTK 3 and GTK 4 applications import from the user's gtk.css.
// It never replaces anything: the only edit to an existing file is one marked block at its end, a backup of the file is made
// first, and Restore removes the block (the result is byte-identical to the backup). Nothing happens without `consent: true`.
import Gio from 'gi://Gio';
import GLib from 'gi://GLib';

import {tokens} from './appearanceTokens.js';
import type {Scheme, Surfaces} from './appearanceTokens.js';

export const BEGIN = '/* >>> niro-glass (managed by Niro Control: Compatibility > Restore removes it) >>> */';
export const END = '/* <<< niro-glass <<< */';
export const GENERATED = 'niro-glass.css';
const HOOK_TARGETS = {4: ['gtk.css', 'gtk-dark.css'], 3: ['gtk.css']};

const rgba = l => `rgba(${l.rgb.join(', ')}, ${+l.a.toFixed(3)})`;

/** Backgrounds only: the window glass, the sidebar and the content surfaces. Text and controls are left to the application. */
export function gtkStylesheet(version: 3 | 4, scheme: Scheme, glass: number, tint: string | undefined, surfaces: Surfaces, disabled = false, solid = false): string {
    // when the scheme could not be established the surfaces are opaque: a wrong guess then costs looks, never readability
    if (solid) { glass = 100; surfaces = {sidebar: 100, content: 100, elevated: 100}; }
    // switched off (or off for GTK): the file stays, so the hook in gtk.css keeps working, but it says nothing
    if (disabled) return `/* Niro Control: appearance for GTK ${version} is switched off. */\n`;
    const t = tokens(scheme, glass, tint, surfaces);
    const sidebar = version === 4 ? '.sidebar-pane, .navigation-sidebar, .sidebar' : '.sidebar, .navigation-sidebar';
    return `/* Generated by Niro Control (${version === 4 ? 'GTK 4 and libadwaita' : 'GTK 3'}, ${scheme}). Edit nothing here: Compatibility regenerates it. */
window.background:not(.solid-csd) { background-color: ${rgba(t.glass)}; }
headerbar, .titlebar { background-color: transparent; box-shadow: none; border-color: ${rgba(t.divider)}; }
${sidebar} { background-color: ${rgba(t.sidebar)}; }
.view, textview, textview text, .content-pane { background-color: ${rgba(t.content)}; }
${version === 3 ? `/* GTK 3 follows its theme, not GNOME's scheme: the text on the surfaces painted here gets a matching colour, so a wrong guess cannot hide it */\n.view, textview text { color: ${rgba(t.text1)}; }\n.sidebar label, .navigation-sidebar label { color: ${rgba(t.text1)}; }\n` : ''}
.boxed-list, list.rich-list { background-color: ${rgba(t.group)}; }
`;
}

const read = path => { try { return new TextDecoder().decode(GLib.file_get_contents(path)[1]); } catch (_e) { return null; } };
const isLink = path => { try { return GLib.file_test(path, GLib.FileTest.IS_SYMLINK); } catch (_e) { return false; } };
const write = (path, text) => {
    GLib.mkdir_with_parents(GLib.path_get_dirname(path), 0o755);
    const tmp = `${path}.niro-tmp`;
    GLib.file_set_contents(tmp, text);
    Gio.File.new_for_path(tmp).move(Gio.File.new_for_path(path), Gio.FileCopyFlags.OVERWRITE, null, null);
};
/** The file a path really is (a symlink is followed, as the user's gtk.css here points at a theme file). */
const target = path => { let p = path, n = 0; while (isLink(p) && n++ < 8) { const l = GLib.file_read_link(p); p = l.startsWith('/') ? l : GLib.build_filenamev([GLib.path_get_dirname(p), l]); } return p; };

// The block is "\n" + BEGIN ... END + "\n": the leading newline is part of it, so removing it gives back the exact original bytes
export const withBlock = (text: string | null, _version: number) => `${withoutBlock(text ?? '')}\n${BEGIN}\n@import url("${GENERATED}");\n${END}\n`;
export function withoutBlock(text: string): string {
    const i = text.indexOf(BEGIN), j = text.indexOf(END);
    if (i < 1 || j < i) return text;
    return text.slice(0, i - 1) + text.slice(j + END.length + 1);
}

/** `scheme` is for GTK 4 (it follows GNOME); `scheme3` for GTK 3 (it follows its theme), `scheme` when absent. */
export interface Options {configDir: string; backupRoot: string; consent: boolean; scheme: Scheme; scheme3?: Scheme; /** GTK 3's scheme is uncertain: opaque surfaces */ solid3?: boolean; glass: number; tint?: string; surfaces: Surfaces; disabled?: boolean}

/** Every file that would be created or changed, for the confirmation dialog. */
export function plan(configDir: string) {
    const files = [];
    for (const v of [4, 3]) {
        const dir = `${configDir}/gtk-${v}.0`;
        files.push({path: `${dir}/${GENERATED}`, change: 'created'});
        for (const name of HOOK_TARGETS[v]) files.push({path: target(`${dir}/${name}`), change: 'one marked block added at the end'});
    }
    return files.filter((f, i) => files.findIndex(g => g.path === f.path) === i);
}

export function status(configDir: string, backupRoot: string) {
    const installed = [4, 3].some(v => (read(target(`${configDir}/gtk-${v}.0/gtk.css`)) ?? '').includes(BEGIN));
    const backups = [];
    try {
        const e = Gio.File.new_for_path(backupRoot).enumerate_children('standard::name', 0, null);
        for (let i = e.next_file(null); i; i = e.next_file(null)) backups.push(i.get_name());
    } catch (_e) { /* none yet */ }
    return {installed, backups: backups.sort()};
}

/** Installs (or refreshes) the integration. Throws, having put every file back, if anything fails half-way. */
export function install(o: Options) {
    if (o.consent !== true) throw new Error('The GTK theme integration changes your gtk.css files: it needs your consent first');
    const stamp = new Date().toISOString().replace(/[:.]/g, '-');
    const backupDir = `${o.backupRoot}/${stamp}`;
    const touched = [];       // {path, before: string|null}
    const manifest = {created: new Date().toISOString(), files: []};
    try {
        for (const v of [4, 3]) {
            const dir = `${o.configDir}/gtk-${v}.0`;
            const gen = `${dir}/${GENERATED}`;
            touched.push({path: gen, before: read(gen)});
            write(gen, gtkStylesheet(v, v === 3 ? (o.scheme3 ?? o.scheme) : o.scheme, o.glass, o.tint, o.surfaces, o.disabled, v === 3 && o.solid3));
            for (const name of HOOK_TARGETS[v]) {
                const real = target(`${dir}/${name}`);
                if (touched.some(t => t.path === real)) continue;
                const before = read(real);
                touched.push({path: real, before});
                if (before !== null && !before.includes(BEGIN)) {
                    const copy = `${backupDir}/${v}-${GLib.path_get_basename(real)}`;
                    write(copy, before);
                    manifest.files.push({path: real, backup: copy});
                } else if (before === null) manifest.files.push({path: real, backup: null});
                write(real, withBlock(before, v));
            }
        }
        if (manifest.files.length) write(`${backupDir}/manifest.json`, JSON.stringify(manifest, null, 2));
    } catch (e) {
        for (const t of touched.reverse()) { try { if (t.before === null) Gio.File.new_for_path(t.path).delete(null); else write(t.path, t.before); } catch (_e) { /* best effort */ } }
        throw new Error(`The GTK theme integration was not installed and your files are as they were: ${e.message}`);
    }
    return {backupDir, files: touched.map(t => t.path)};
}

/** Removes the integration: the marked blocks and the generated files. Backups are kept. */
export function restore(configDir: string) {
    const removed = [];
    for (const v of [4, 3]) {
        const dir = `${configDir}/gtk-${v}.0`;
        for (const name of HOOK_TARGETS[v]) {
            const real = target(`${dir}/${name}`);
            const text = read(real);
            if (text?.includes(BEGIN)) { const out = withoutBlock(text); if (out === '') Gio.File.new_for_path(real).delete(null); else write(real, out); removed.push(real); }
        }
        const gen = `${dir}/${GENERATED}`;
        if (GLib.file_test(gen, GLib.FileTest.EXISTS)) { Gio.File.new_for_path(gen).delete(null); removed.push(gen); }
    }
    return removed;
}

/**
 * Rewrites the generated stylesheets after a Look or scheme change, atomically, and only the ones whose content would differ (a
 * small change elsewhere in the Look does not touch the files). Does nothing when the integration is not installed.
 * Returns the paths it rewrote.
 */
export function refresh(o: Omit<Options, 'consent' | 'backupRoot'>): string[] {
    if (!status(o.configDir, '/nonexistent').installed) return [];
    const rewritten = [];
    for (const v of [4, 3]) {
        const path = `${o.configDir}/gtk-${v}.0/${GENERATED}`;
        const next = gtkStylesheet(v, v === 3 ? (o.scheme3 ?? o.scheme) : o.scheme, o.glass, o.tint, o.surfaces, o.disabled, v === 3 && o.solid3);
        if (read(path) === next) continue;
        write(path, next);
        rewritten.push(path);
    }
    return rewritten;
}
