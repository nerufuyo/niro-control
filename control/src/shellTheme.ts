// The GNOME Shell side of Universal Appearance: one narrowly scoped stylesheet for the surfaces Niro does not draw itself (top bar,
// popups and system menus, Quick Settings, notifications, the date menu, the Overview's search and workspace thumbnails, the app
// folder dialog, the window switcher). Pure: the extension loads the text, tests check it.
// The shell's own text colour decides the surface: a shell theme with light text (the stock dark look, MacTahoe-Dark) gets dark
// surfaces, one with dark text (Yaru's light look) gets light ones, so the text the theme draws is never put on a background it
// was not made for. The extension measures that colour from the live shell (see `isDarkSurface`) and passes it in per group.
// Foreground colours are never set here, and nothing lowers an opacity: only backgrounds carry alpha, never below the floors.
import {EDGE, hexToRgb} from './appearanceTokens.js';
import type {RGB} from './appearanceTokens.js';

/** Per group of surfaces: true when the shell draws light text there, so the surface is dark. */
export interface ShellDark {panel: boolean; popup: boolean; quick: boolean; overview: boolean}
export interface ShellLook {
    accent: string; tint?: string; dark: ShellDark;
    /** Solidity of the surfaces, 0 to 100, as effective() gives them (safe mode and the Solid preset give 100) */
    sidebar: number; content: number; elevated: number;
}

/** The selectors this stylesheet is allowed to touch: a test keeps it from growing into a theme. */
export const SHELL_SELECTORS = ['#panel', '.popup-menu-content', '.candidate-popup-content', '.quick-settings', '.notification-banner', '.message-list .message',
    '.datemenu-popover', '.search-entry', '.app-folder-dialog', '.switcher-list', '.workspace-thumbnails .workspace-thumbnail', '.quick-toggle:checked',
    '.quick-menu-toggle:checked', '.popup-menu-item:focus', '.popup-menu-item:active', '.slider'];

const clamp = (n: number, lo: number, hi: number) => Math.min(hi, Math.max(lo, Number.isFinite(n) ? n : lo));
const lum = ([r, g, b]: RGB) => [r, g, b].map(v => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; }).reduce((s, v, i) => s + v * [0.2126, 0.7152, 0.0722][i], 0);
/** The base of the dark surfaces: the Look tint when it is dark, else a neutral. */
export function baseColor(tint?: string): RGB {
    const t = hexToRgb(tint ?? '');
    return t && lum(t) < 0.12 ? t : [28, 28, 34];
}
const lift = ([r, g, b]: RGB, by: number): RGB => [r, g, b].map(v => Math.min(255, v + by)) as RGB;
/** A text colour (0 to 1 each) is light when its luminance is above the middle: the surface under it should then be dark. */
export function isDarkSurface(fg: {r: number; g: number; b: number}): boolean {
    return lum([fg.r * 255, fg.g * 255, fg.b * 255]) > 0.4;
}
const rgba = (c: RGB, a: number) => `rgba(${c.join(', ')}, ${+clamp(a, 0, 1).toFixed(3)})`;

export function shellStylesheet(look: ShellLook): string {
    const accent = hexToRgb(look.accent) ?? [232, 71, 43];
    const darkBase = baseColor(look.tint), lightBase: RGB = [250, 250, 252];
    const layer = (dark: boolean) => {
        const base = dark ? darkBase : lightBase;
        return {surface: rgba(base, clamp(look.content, 70, 100) / 100), raised: rgba(dark ? lift(base, 8) : [255, 255, 255], clamp(look.elevated, 80, 100) / 100),
            border: dark ? EDGE.borderDark : EDGE.borderLight, shadow: dark ? EDGE.shadowDark : EDGE.shadowLight};
    };
    const bar = rgba(look.dark.panel ? darkBase : lightBase, clamp(look.sidebar, 70, 100) / 100);
    const p = layer(look.dark.popup), q = layer(look.dark.quick), o = layer(look.dark.overview);
    const accentSolid = rgba(accent, 1), accentSoft = rgba(accent, 0.35);
    return `/* Generated by Niro Control: Universal Appearance for GNOME Shell. Backgrounds, borders and shadows only. */
#panel { background-color: ${bar}; }
.popup-menu-content, .candidate-popup-content { background-color: ${p.raised}; border: 1px solid ${p.border}; border-radius: ${EDGE.radiusPopup}px; box-shadow: ${p.shadow}; }
.quick-settings { background-color: ${q.raised}; border: 1px solid ${q.border}; border-radius: ${EDGE.radiusSheet}px; box-shadow: ${q.shadow}; }
.datemenu-popover { background-color: ${p.raised}; border: 1px solid ${p.border}; box-shadow: ${p.shadow}; }
.notification-banner { background-color: ${p.raised}; border: 1px solid ${p.border}; border-radius: ${EDGE.radiusCard}px; box-shadow: ${p.shadow}; }
.message-list .message { background-color: ${p.surface}; border-radius: ${EDGE.radiusCard}px; }
.search-entry { background-color: ${o.surface}; border: 1px solid ${o.border}; }
.app-folder-dialog { background-color: ${o.raised}; border: 1px solid ${o.border}; }
.switcher-list { background-color: ${o.raised}; border: 1px solid ${o.border}; border-radius: ${EDGE.radiusPopup}px; box-shadow: ${o.shadow}; }
.workspace-thumbnails .workspace-thumbnail { border-radius: 10px; border: 1px solid ${o.border}; }
.quick-toggle:checked, .quick-menu-toggle:checked { background-color: ${accentSolid}; }
.popup-menu-item:focus, .popup-menu-item:active { background-color: ${accentSoft}; }
.slider { -barlevel-active-background-color: ${accentSolid}; }
`;
}
