#!/usr/bin/env python3
"""Validates tests/uat/matrix.csv and renders the UAT matrix (docs/motion/uat/matrix.md) and the acceptance roll-up.

usage: uat-report.py [--csv tests/uat/matrix.csv] [--md docs/motion/uat/matrix.md] [--check]

Rules it enforces, so a desktop scenario cannot be marked passed without having been run:
  Pass     needs tester, date, actual and evidence (a file, a probe JSON, a video or a journal excerpt)
  Fail     needs class (functional | cosmetic | performance | environment), severity (S1..S4), actual and evidence
  Blocked  needs class environment (or the reason in actual) and a date
  Not run  must have every result field empty
Severity: S1 broken or unsafe (crash, stuck grab, lost input, data loss) / S2 visible defect on a common path / S3 minor, rare or subtle / S4 cosmetic.
Exit status 1 with --check when any row breaks a rule. It decides nothing about animation parameters.
"""
import argparse, csv, sys

ACCEPT = [
    ('No functional regressions', ['UAT-REG-01', 'UAT-SRCH-04', 'UAT-DOCK-05', 'UAT-ISL-04']),
    ('No focus or input-grab conflicts', ['UAT-X-01', 'UAT-X-02', 'UAT-SRCH-05', 'UAT-LIFE-02']),
    ('No visible content teleporting or significant clipping', ['UAT-ISL-01', 'UAT-ISL-02', 'UAT-ISL-03', 'UAT-ISL-04', 'UAT-ISL-05', 'UAT-ISL-06']),
    ('No persistent Search-Island overlap', ['UAT-SRCH-05', 'UAT-SRCH-06']),
    ('Smooth Dock magnification under real pointer movement', ['UAT-DOCK-01', 'UAT-DOCK-02', 'UAT-DOCK-03', 'UAT-FP-01']),
    ('Stable Search interaction during rapid typing', ['UAT-SRCH-01', 'UAT-SRCH-02', 'UAT-SRCH-03']),
    ('Correct extension disable/enable lifecycle', ['UAT-LIFE-01', 'UAT-LIFE-02', 'UAT-LIFE-03', 'UAT-LIFE-04']),
    ('Reduced-motion preferences respected', ['UAT-A11Y-01', 'UAT-A11Y-02']),
]
STATUS = ['Not run', 'Pass', 'Fail', 'Blocked']
CLASSES = ['functional', 'cosmetic', 'performance', 'environment']
SEV = ['S1', 'S2', 'S3', 'S4']


def validate(r):
    e, s = [], r['status']
    f = lambda k: r[k].strip()
    if s not in STATUS: return [f"status '{s}' is not one of {STATUS}"]
    if s == 'Not run':
        for k in ('actual', 'evidence', 'class', 'severity', 'tester', 'date'):
            if f(k): e.append(f'Not run but {k} is filled')
    if s == 'Pass':
        for k in ('tester', 'date', 'actual', 'evidence'):
            if not f(k): e.append(f'Pass needs {k}')
        if f('severity') or f('class'): e.append('Pass must not carry a class or severity')
    if s == 'Fail':
        for k in ('tester', 'date', 'actual', 'evidence', 'action'):
            if not f(k): e.append(f'Fail needs {k}')
        if f('class') not in CLASSES: e.append(f'Fail needs class in {CLASSES}')
        if f('severity') not in SEV: e.append(f'Fail needs severity in {SEV}')
    if s == 'Blocked':
        for k in ('date', 'actual'):
            if not f(k): e.append(f'Blocked needs {k} (what was missing)')
        if f('class') != 'environment': e.append("Blocked needs class 'environment'")
    return e


def verdict(rows):
    sts = [r['status'] for r in rows]
    if 'Fail' in sts: return 'FAIL'
    if all(x == 'Pass' for x in sts): return 'PASS'
    if 'Not run' in sts: return 'NOT VERIFIED'
    return 'BLOCKED (partly)'


def esc(x): return x.replace('|', '\\|').replace('\n', ' ')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--csv', default='tests/uat/matrix.csv'); ap.add_argument('--md'); ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    rows = list(csv.DictReader(open(a.csv, newline='')))
    ids = {r['id'] for r in rows}
    bad = []
    if len(ids) != len(rows): bad.append('duplicate test ids')
    for _, tid in ACCEPT:
        for i in tid:
            if i not in ids: bad.append(f'acceptance map names missing test {i}')
    for r in rows:
        for e in validate(r): bad.append(f"{r['id']}: {e}")
    by = {r['id']: r for r in rows}
    counts = {s: sum(r['status'] == s for r in rows) for s in STATUS}
    out = ['# Desktop UAT matrix', '',
           'Generated by `tests/uat/uat-report.py` from `tests/uat/matrix.csv`. Do not edit this file: fill the CSV, rerun the tool.', '',
           f"Results: {counts['Pass']} Pass, {counts['Fail']} Fail, {counts['Blocked']} Blocked, {counts['Not run']} Not run of {len(rows)}. "
           'A scenario is Pass only if it was executed on a real desktop with evidence attached. Headless results are listed under "Headless basis" and prove nothing here.', '',
           '| Test ID | Component | Scenario | Expected behavior | Actual behavior | Result | Evidence | Severity | Recommended action |', '|---|---|---|---|---|---|---|---|---|']
    for r in rows:
        sev = (r['severity'] + (' / ' + r['class'] if r['class'] else '')) if r['severity'] or r['class'] else ''
        out.append(f"| {r['id']} | {r['component']} | {esc(r['scenario'])} | {esc(r['expected'])} | {esc(r['actual']) or 'not executed'} | {r['status']} | {esc(r['evidence'])} | {esc(sev)} | {esc(r['action'])} |")
    out += ['', '## Acceptance criteria', '', '| Criterion | Result | Tests |', '|---|---|---|']
    vs = []
    for name, tid in ACCEPT:
        v = verdict([by[i] for i in tid if i in by]); vs.append(v)
        out.append(f"| {name} | {v} | {', '.join(tid)} |")
    ready = all(v == 'PASS' for v in vs) and not any(r['status'] == 'Fail' for r in rows)
    out += ['', '## Recommendation', '',
            'Push or PR may be recommended: every criterion passed on a real desktop.' if ready else
            'Push or PR is **not** recommended yet: the criteria above are not all PASS. Failed, blocked or unrun scenarios need results first.']
    if a.md: open(a.md, 'w').write('\n'.join(out) + '\n')
    print('\n'.join(out) if not a.md else f"{counts} -> {a.md}")
    if bad:
        print('\nRULE VIOLATIONS:\n  ' + '\n  '.join(bad), file=sys.stderr)
        if a.check: sys.exit(1)


if __name__ == '__main__':
    main()
